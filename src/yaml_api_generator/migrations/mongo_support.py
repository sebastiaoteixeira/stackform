"""Native versioned migrations for MongoDB datastores declared in a spec.

Mirrors the Alembic driver: ordered forward/backward revisions live as JSON
files under ``<spec>/mongo_migrations/<datastore>/``, and the applied history is
persisted in the datastore itself in a ``migrations`` collection (the analogue of
Alembic's version table). Index and unique-constraint changes are autogenerated
from the same spec fields that ``initialize_indexes`` materializes on connect;
data reshapes that Mongo cannot express declaratively use ``run_handler`` steps
backed by dotted-path handlers. A spec graduates from create-on-connect by
stamping a baseline when the collections and indexes already exist.
"""

import asyncio
import importlib
import json
from contextlib import asynccontextmanager
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Awaitable, Callable

import click
from pymongo import AsyncMongoClient

from yaml_api_generator.ir import IRDocument, IRMongo
from yaml_api_generator.parsers.yaml_parser import load_and_generate_ir
from yaml_api_generator.server.common.loader import mongo_connection_params
from yaml_api_generator.server.common.repositories.mongodb import (
    unique_index_partial_filter,
)

STORE_COLLECTION = "migrations"


@dataclass(frozen=True)
class Revision:
    revision: str
    down_revision: str | None
    message: str
    operations: list[dict[str, Any]]


@dataclass
class MongoMigrationConfig:
    spec_path: str
    datastore: str
    directory: Path
    ir: IRDocument
    connect: Callable[[], Any]


def mongo_migrations_dir(spec_path: str, datastore: str) -> Path:
    return Path(spec_path).resolve().parent / "mongo_migrations" / datastore


def resolve_mongo(ir: IRDocument, datastore: str | None) -> str:
    mongos = {n: d for n, d in ir.datastores.items() if isinstance(d, IRMongo)}
    if not mongos:
        raise ValueError("No MongoDB datastore declared in this spec")
    if datastore is not None:
        if datastore not in mongos:
            raise ValueError(f"'{datastore}' is not a MongoDB datastore")
        return datastore
    if len(mongos) > 1:
        raise ValueError("Multiple MongoDB datastores; pass --datastore to choose one")
    return next(iter(mongos))


def make_config(spec_path: str, datastore: str | None = None) -> MongoMigrationConfig:
    ir = load_and_generate_ir(spec_path).ir
    name = resolve_mongo(ir, datastore)
    directory = mongo_migrations_dir(spec_path, name)
    directory.mkdir(parents=True, exist_ok=True)
    uri, database = mongo_connection_params(ir, name)

    @asynccontextmanager
    async def connect():
        client = AsyncMongoClient(uri)
        try:
            yield client[database]
        finally:
            await client.close()

    return MongoMigrationConfig(
        spec_path=str(spec_path),
        datastore=name,
        directory=directory,
        ir=ir,
        connect=connect,
    )


def load_revisions(directory: Path) -> list[Revision]:
    revisions = [
        Revision(**json.loads(path.read_text())) for path in directory.glob("*.json")
    ]
    return sorted(revisions, key=lambda revision: revision.revision)


def _desired_indexes(ir: IRDocument, datastore: str) -> list[tuple[str, str]]:
    result: list[tuple[str, str]] = []
    for name, collection in ir.collections.items():
        if (collection.datastore or ir.default_datastore) != datastore:
            continue
        for field_name, cfg in collection.fields.items():
            if isinstance(cfg, dict) and cfg.get("unique"):
                result.append((name, field_name))
    return result


def _known_indexes(revisions: list[Revision]) -> set[tuple[str, str]]:
    known: set[tuple[str, str]] = set()
    for revision in revisions:
        for op in revision.operations:
            key = (op.get("collection"), op.get("field"))
            if op["op"] == "create_index":
                known.add(key)
            elif op["op"] == "drop_index":
                known.discard(key)
    return known


def autogenerate(
    ir: IRDocument, datastore: str, revisions: list[Revision]
) -> list[dict[str, Any]]:
    desired = _desired_indexes(ir, datastore)
    known = _known_indexes(revisions)
    ops = [
        {"op": "create_index", "collection": coll, "field": name, "unique": True}
        for coll, name in desired
        if (coll, name) not in known
    ]
    ops += [
        {"op": "drop_index", "collection": coll, "field": name, "unique": True}
        for coll, name in sorted(known - set(desired))
    ]
    return ops


def _write_revision(
    directory: Path,
    revision: str,
    down_revision: str | None,
    message: str,
    operations: list[dict[str, Any]],
) -> Path:
    path = directory / f"{revision}_{message.replace(' ', '_')}.json"
    path.write_text(
        json.dumps(
            {
                "revision": revision,
                "down_revision": down_revision,
                "message": message,
                "operations": operations,
            },
            indent=2,
        )
    )
    return path


def _collections_for(ir: IRDocument, datastore: str) -> set[str]:
    return {
        name
        for name, collection in ir.collections.items()
        if (collection.datastore or ir.default_datastore) == datastore
    }


def _index_name(op: dict[str, Any]) -> str:
    return op.get("name") or f"{op['field']}_1"


async def _create_index(db: Any, op: dict[str, Any]) -> None:
    kwargs: dict[str, Any] = {"name": _index_name(op)}
    if op.get("unique"):
        kwargs["unique"] = True
        kwargs["partialFilterExpression"] = unique_index_partial_filter(op["field"])
    await db[op["collection"]].create_index(op["field"], **kwargs)


async def _drop_index(db: Any, op: dict[str, Any]) -> None:
    await db[op["collection"]].drop_index(_index_name(op))


def _load_handler(dotted_path: str) -> Callable[[Any], Awaitable[None]]:
    module_path, _, attr = dotted_path.rpartition(".")
    if not module_path:
        raise ValueError(f"Invalid handler path: {dotted_path}")
    return getattr(importlib.import_module(module_path), attr)


async def _run_handler(db: Any, op: dict[str, Any], direction: str) -> None:
    dotted = op.get(direction)
    if dotted is None:
        raise ValueError(f"run_handler revision has no '{direction}' handler")
    await _load_handler(dotted)(db)


async def _apply(db: Any, op: dict[str, Any], direction: str) -> None:
    if op["op"] == "run_handler":
        await _run_handler(db, op, direction)
        return
    forward = op["op"] == "create_index"
    if direction == "down":
        forward = not forward
    await (_create_index if forward else _drop_index)(db, op)


async def _applied_ids(db: Any) -> set[str]:
    docs = await db[STORE_COLLECTION].find({}).to_list(length=None)
    return {doc["_id"] for doc in docs}


async def _record(db: Any, revision: Revision) -> None:
    await db[STORE_COLLECTION].insert_one(
        {
            "_id": revision.revision,
            "down_revision": revision.down_revision,
            "message": revision.message,
            "applied_at": datetime.now(timezone.utc),
        }
    )


async def _forget(db: Any, revision_id: str) -> None:
    await db[STORE_COLLECTION].delete_one({"_id": revision_id})


async def _schema_present(config: MongoMigrationConfig, db: Any) -> bool:
    collections = _collections_for(config.ir, config.datastore)
    if not collections:
        return False
    existing = set(await db.list_collection_names())
    if not collections <= existing:
        return False
    for coll, name in _desired_indexes(config.ir, config.datastore):
        indexes = await db[coll].list_indexes().to_list(length=None)
        if f"{name}_1" not in {index["name"] for index in indexes}:
            return False
    return True


async def _maybe_stamp_baseline(config: MongoMigrationConfig, revision: Revision) -> None:
    async with config.connect() as db:
        if await _schema_present(config, db):
            await _record(db, revision)


def new_revision(config: MongoMigrationConfig, message: str) -> None:
    revisions = load_revisions(config.directory)
    operations = autogenerate(config.ir, config.datastore, revisions)
    revision_id = f"{len(revisions) + 1:04d}"
    down_revision = revisions[-1].revision if revisions else None
    _write_revision(config.directory, revision_id, down_revision, message, operations)
    if not revisions:
        asyncio.run(
            _maybe_stamp_baseline(
                config, Revision(revision_id, down_revision, message, operations)
            )
        )


async def _upgrade(config: MongoMigrationConfig, target: str) -> None:
    revisions = load_revisions(config.directory)
    async with config.connect() as db:
        applied = await _applied_ids(db)
        pending = [r for r in revisions if r.revision not in applied]
        if target != "head":
            pending = [r for r in pending if r.revision <= target]
        for revision in pending:
            for op in revision.operations:
                await _apply(db, op, "up")
            await _record(db, revision)


async def _downgrade(config: MongoMigrationConfig, target: str) -> None:
    revisions = load_revisions(config.directory)
    async with config.connect() as db:
        applied_ids = await _applied_ids(db)
        applied = [r for r in revisions if r.revision in applied_ids]
        if target == "-1":
            revert = applied[-1:]
        elif target == "base":
            revert = applied[:]
        else:
            revert = [r for r in applied if r.revision > target]
        for revision in reversed(revert):
            for op in reversed(revision.operations):
                await _apply(db, op, "down")
            await _forget(db, revision.revision)


async def _status(config: MongoMigrationConfig) -> None:
    async with config.connect() as db:
        applied = sorted(await _applied_ids(db))
    click.echo(f"Current revision: {applied[-1] if applied else '(base)'}")


def upgrade(config: MongoMigrationConfig, target: str = "head") -> None:
    asyncio.run(_upgrade(config, target))


def downgrade(config: MongoMigrationConfig, target: str = "-1") -> None:
    asyncio.run(_downgrade(config, target))


def status(config: MongoMigrationConfig) -> None:
    asyncio.run(_status(config))


def history(config: MongoMigrationConfig) -> None:
    for revision in reversed(load_revisions(config.directory)):
        base = revision.down_revision or "(base)"
        click.echo(f"{base} -> {revision.revision}: {revision.message}")
